def build_package(base_zip_name, out_zip_name):
    base_zip_path = os.path.join(CACHE_DIR, base_zip_name)
    out_zip_path = os.path.join(OUT_DIR, out_zip_name)
    print(f"Building: {out_zip_name}")

    with zipfile.ZipFile(base_zip_path, 'r') as z_in, zipfile.ZipFile(out_zip_path, 'w', compression=zipfile.ZIP_DEFLATED) as z_out:
        for info in z_in.infolist():
            fn = info.filename
            if not fn.startswith('Electron.app'):
                continue
            
            subpath = fn[len('Electron.app'):]
            new_fn = APP_DIR + subpath
            
            data = z_in.read(info)
            
            if fn == 'Electron.app/Contents/MacOS/Electron':
                new_fn = APP_DIR + '/Contents/MacOS/' + EXEC_NAME
            elif fn == 'Electron.app/Contents/Info.plist':
                pl = plistlib.loads(data)
                pl['CFBundleName'] = APP_NAME
                pl['CFBundleDisplayName'] = APP_NAME
                pl['CFBundleIdentifier'] = 'com.taffy.desktoppet'
                pl['CFBundleExecutable'] = EXEC_NAME
                pl['CFBundleIconFile'] = 'electron.icns'
                data = plistlib.dumps(pl)
            elif fn == 'Electron.app/Contents/Resources/electron.icns':
                data = icns_data

            new_info = zipfile.ZipInfo(new_fn)
            new_info.external_attr = info.external_attr
            new_info.compress_type = info.compress_type
            new_info.date_time = info.date_time
            new_info.flag_bits |= 0x800
            z_out.writestr(new_info, data)

        # 写入 app.asar
        asar_info = zipfile.ZipInfo(APP_DIR + '/Contents/Resources/app.asar')
        asar_info.external_attr = 0o100644 << 16
        asar_info.compress_type = zipfile.ZIP_DEFLATED
        asar_info.flag_bits |= 0x800
        z_out.writestr(asar_info, asar_data)

        # 写入修复脚本
        cmd_name = b'\xe4\xb8\x80\xe9\x94\xae\xe8\xa7\xa3\xe5\x86\xb3Mac\xe6\x8f\x90\xe7\xa4\xba\xe6\x89\x93\xe4\xb8\x8d\xe5\xbc\x80.command'.decode('utf-8')
        cmd_info = zipfile.ZipInfo(cmd_name)
        cmd_info.external_attr = 0o100755 << 16
        cmd_info.compress_type = zipfile.ZIP_DEFLATED
        cmd_info.flag_bits |= 0x800
        z_out.writestr(cmd_info, fix_script)

        # 写入说明文件
        txt_name = b'macOS\xe4\xbd\xbf\xe7\x94\xa8\xe8\xaf\xb4\xe6\x98\x8e.txt'.decode('utf-8')
        txt_info = zipfile.ZipInfo(txt_name)
        txt_info.external_attr = 0o100644 << 16
        txt_info.compress_type = zipfile.ZIP_DEFLATED
        txt_info.flag_bits |= 0x800
        z_out.writestr(txt_info, readme_bytes)

    print(f"Success: {out_zip_name} ({os.path.getsize(out_zip_path)/(1024*1024):.1f}MB)")
    desktop_dst = os.path.join(DESKTOP_DIR, out_zip_name)
    shutil.copyfile(out_zip_path, desktop_dst)
    print(f"Copied to Desktop: {desktop_dst}")

